// "Tab Guy, ep. 1 — Blues in A": a three-piece (the band character sheet, public/band/) plays a shuffle blues in A on a club stage. The guitarist
// (Tab Guy) is asked to jump in, searches his phone for a tab, misses twice, freezes; the bassist listens one beat and plays the lick by ear,
// jumps on the last hit. One timeline for the soundtrack (audio.mjs), the voices (voice.mjs) and every frame (src/jam/JamScene.tsx).
export const FPS = 60;
export const BPM = 120;
export const BEAT = 60 / BPM;                 // 0.5 s
export const BAR = 4 * BEAT;                  // 2 s
export const SWING = 2 / 3;                   // the off-beat eighth sits at 2/3 of the beat (shuffle)
export const T0 = 2.0;                        // bar 1, after a one-bar count-in

const bar = (b) => T0 + (b - 1) * BAR;        // bars are 1-based, like the on-screen counter
const at = (b, beat, off = 0) => bar(b) + (beat - 1) * BEAT + off * BEAT;   // off = 0 on the beat, SWING on the shuffle eighth

// Bars 1–9 of a 12-bar in A (quick change in bar 2); the film cuts to the big A7 on the downbeat of bar 10.
export const CHORDS = ['A', 'D', 'A', 'A', 'D', 'D', 'A', 'A', 'E'];
const ROOT = { A: 33, D: 38, E: 40 };          // bass roots, MIDI (A1 D2 E2)

export const T = {
  count: [0, 1, 2, 3].map((i) => i * BEAT),   // sticks: 1-2-3-4
  ask: at(1, 3),                               // bassist: "Blues in A. Just jump in!"
  phone: bar(3),                               // camera on the guitarist, the phone comes up
  miss1: at(4, 1),                             // first wrong strum (F major over A7)
  miss2: at(5, 1),                             // second (Bb major over D7)
  freeze: bar(6),                              // he stops; the band plays on
  listen: bar(7),                              // camera to the bassist: one beat of listening
  lick: at(7, 2),                              // the lick, by ear
  fill: at(9, 4),                              // drum roll into the hit (also the bassist's wind-up)
  hit: bar(10),                                // the big A7 + the jump
  card: bar(10) + 0.95,                        // end card
};
export const DURATION = T.card + 3.0;          // ≈ 23.9 s

// Walking boogie bass, eight swung eighths per bar: root, 3rd, 5th, 6th, b7, 6th, 5th, 3rd.
const WALK = [0, 4, 7, 9, 10, 9, 7, 4];
export const BASS = [];
for (let b = 1; b <= 9; b++) {
  if (b === 7 || b === 8) continue;            // while the bassist plays the lick the walk stops
  WALK.forEach((iv, i) => BASS.push({ t: at(b, 1 + (i >> 1), i % 2 ? SWING : 0), midi: ROOT[CHORDS[b - 1]] + iv, dur: i % 2 ? BEAT * (1 - SWING) : BEAT * SWING }));
}

// The lick (A minor pentatonic with the blue 3rd → major 3rd slide) around the 5th-fret box of the bass neck: [bar, beat, off, midi, beats long].
const LICK = [
  [7, 2, 0, 36, 0.33], [7, 2, SWING, 37, 0.33], [7, 3, 0, 40, 0.5], [7, 3, SWING, 43, 0.33], [7, 4, 0, 45, 1.0],
  [8, 1, SWING, 48, 0.33], [8, 2, 0, 45, 0.5], [8, 2, SWING, 43, 0.33], [8, 3, 0, 40, 0.5], [8, 3, SWING, 37, 0.33], [8, 4, 0, 33, 0.9],
];
export const LEAD = LICK.map(([b, beat, off, midi, len]) => ({ t: at(b, beat, off), midi, dur: len * BEAT }));
// A neck position for each lick note (4-string bass, E1 A1 D2 G2, frets 0–12) for the fretboard inset: string 0 = E (low) … 3 = G;
// of the strings that can play the note, the one closest to the 5th-fret box.
export const LEAD_POS = LEAD.map((n) => [28, 33, 38, 43].map((open, s) => ({ s, f: n.midi - open })).filter((p) => p.f >= 0 && p.f <= 12).sort((x, y) => Math.abs(x.f - 6) - Math.abs(y.f - 6))[0]);

// Drums: shuffle — kick 1 & 3, snare 2 & 4, hats on every beat and every swung eighth; stops for the fill.
export const KICKS = [], SNARES = [], HATS = [];
for (let b = 1; b <= 9; b++) for (let beat = 1; beat <= 4; beat++) {
  const t = at(b, beat);
  if (t >= T.fill - 1e-6) continue;
  (beat % 2 ? KICKS : SNARES).push(t);
  HATS.push(t, at(b, beat, SWING));
}
export const FILL = [0, 0.125, 0.25, 0.375].map((o) => T.fill + o * 1);  // four sixteenths into the hit
export const BEATS = Array.from({ length: 9 * 4 }, (_, i) => T0 + i * BEAT).filter((t) => t < T.hit);

