// Cuts the Android screen recording of Ear Warrior's first melody (learn/rec/first-melody.mp4, 30 fps CFR, recorded 2026-11-09 on the
// emulator with adb input taps) down to the seconds the film shows → public/learn-app.mp4, and writes learn/app.mjs: the caption steps and
// the app's sounds at their times in the cut (the recording has no audio; learn/audio.mjs plays the app's own clips at these marks).
//   node learn/cut-app.mjs
// Times below are in the recording: each tap mark from the adb script + 1.57 s (the lag found from the scene changes).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, 'rec', 'first-melody.mp4'), OUT = join(here, '..', 'public', 'learn-app.mp4');

// [from, to, speed] in the recording
const SEGS = [
  [2.45, 5.1, 1.0],     // Listen: tap ▶, the four notes play
  [7.05, 10.75, 1.6],   // Play: G G G on the D string, then a wrong 4th note, Check
  [10.75, 12.3, 1.0],   // "Almost: 3 of 4 right · Note 4 is off. It should be lower."
  [13.3, 16.6, 1.8],    // Try again → the lower fret → Check
  [16.6, 18.4, 1.0],    // "You played it by ear · That was Beethoven's Fifth. No tabs, just your ear."
];
const EVENTS = [
  { at: 2.75, clip: 'fifthfirst' },
  { at: 7.21, midi: 55 }, { at: 7.91, midi: 55 }, { at: 8.59, midi: 55 }, { at: 9.40, midi: 52 },
  { at: 10.52, wrong: true },
  { at: 13.43, tick: true }, { at: 15.15, midi: 51 },
  { at: 16.54, right: true },
];
const STEPS = [
  { seg: 0, label: '1 · Hear it', color: '#8ee8ff' },
  { seg: 1, label: '2 · Find it on the neck', color: '#ffd43b' },
  { seg: 2, label: '3 · Instant check', color: '#ff9ac2' },
  { seg: 4, label: 'By ear ✓', color: '#7cf0a8' },
];

let acc = 0;
const starts = SEGS.map(([a, b, sp]) => { const s = acc; acc += (b - a) / sp; return s; });
const toCut = (t) => { const i = SEGS.findIndex(([a, b]) => t >= a && t < b); return i < 0 ? null : starts[i] + (t - SEGS[i][0]) / SEGS[i][2]; };

const parts = SEGS.map(([a, b, sp], i) => `[0:v]trim=${a}:${b},setpts=(PTS-STARTPTS)/${sp},fps=60[v${i}]`).join(';');
const filter = `${parts};${SEGS.map((_, i) => `[v${i}]`).join('')}concat=n=${SEGS.length}:v=1:a=0,scale=900:-2[out]`;
execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', SRC, '-filter_complex', filter, '-map', '[out]', '-c:v', 'libx264', '-crf', '16', '-pix_fmt', 'yuv420p', OUT]);

const sounds = EVENTS.map((e) => ({ ...e, at: toCut(e.at) })).filter((e) => e.at !== null).map((e) => ({ ...e, at: +e.at.toFixed(3) }));
const steps = STEPS.map((s) => ({ at: +starts[s.seg].toFixed(3), label: s.label, color: s.color }));
writeFileSync(join(here, 'app.mjs'), '// Generated by learn/cut-app.mjs — do not edit.\nexport default ' + JSON.stringify({ length: +acc.toFixed(3), steps, sounds }, null, 2) + ';\n');
console.log(`cut-app: ${acc.toFixed(2)} s → ${OUT}`);
