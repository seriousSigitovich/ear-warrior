// Builds the served melody library: reads the ABC source (src/services/melody/library.abc) and writes
// src/services/melody/library.ts. Each tune's notes are moved by whole octaves onto the 12-fret neck,
// and its scale is derived from the notes, so the label can never disagree with them.
//
//   npm run library
//
// Each tune in the ABC file is one X: block with, besides the usual T:, Q:, M:, L: and K: fields:
//   %%id <id>          stable, hyphen-free id (prefixes the melody id and names the audio clip)
//   %%level <1-9>      difficulty rank
//   %%source <text>    where the notes were taken from
//   %%notes <tokens>   optional, any number of lines: the melody as "pitch:beats" tokens (e.g. extracted
//                      from a MIDI file); when present it replaces the ABC music lines
// Write repeats out in full (a repeat sign only breaks the tune into parts here) and fold rests into
// the note before them.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseAbc } from '../src/services/melody/abc';
import { classify, fitToNeck, parseMelody } from '../src/services/melody/classify';
import { MAX_RANK, MIN_RANK } from '../src/services/melody/levels';

const DIR = join(__dirname, '..', 'src', 'services', 'melody');
const NAMES = ['C', 'C#', 'D', 'Eb', 'E', 'F', 'F#', 'G', 'Ab', 'A', 'Bb', 'B'];

function directive(block: string, name: string): string | undefined {
  return block.match(new RegExp(`^%%${name}[ \\t]+(.+)$`, 'm'))?.[1].trim();
}

function field(block: string, letter: string): string | undefined {
  return block.match(new RegExp(`^${letter}:[ \\t]*(.+)$`, 'm'))?.[1].trim();
}

/** "1/4=120" → 120; "3/8=60" → 90 (always quarter-note beats per minute). */
function quarterBpm(q: string, id: string): number {
  const m = q.match(/^(\d+)\/(\d+)\s*=\s*(\d+)$/);
  if (!m) throw new Error(`${id}: Q: must look like 1/4=120, got "${q}"`);
  return Math.round(Number(m[3]) * (Number(m[1]) / Number(m[2])) * 4);
}

function beatsText(beats: number): string {
  return String(Number(beats.toFixed(4)));
}

function abcNotes(block: string, id: string): { midi: number; beats: number }[] {
  const { tunes: parsed, skipped } = parseAbc(block);
  if (skipped.length > 0 || parsed.length !== 1) throw new Error(`${id}: ${skipped[0]?.reason ?? 'not one tune'}`);
  return parsed[0].segments.flat();
}

/** The `%%notes` lines of a block, if any. */
function rawNotes(block: string): { midi: number; beats: number }[] | undefined {
  const lines = [...block.matchAll(/^%%notes[ \t]+(.+)$/gm)].map((m) => m[1]);
  return lines.length > 0 ? parseMelody(lines.join(' ')) : undefined;
}

const source = readFileSync(join(DIR, 'library.abc'), 'utf8');
const blocks = source.split(/^(?=X:)/m).filter((b) => b.startsWith('X:'));
const tunes = blocks.map((block) => {
  const id = directive(block, 'id');
  if (!id || !/^[a-z0-9]+$/.test(id)) throw new Error(`Bad or missing %%id in:\n${block.slice(0, 200)}`);
  const rank = Number(directive(block, 'level'));
  if (!Number.isInteger(rank) || rank < MIN_RANK || rank > MAX_RANK) throw new Error(`${id}: bad %%level`);
  const title = field(block, 'T');
  const key = field(block, 'K');
  const q = field(block, 'Q');
  const from = directive(block, 'source') ?? 'from memory, unchecked';
  if (!title || !key || !q) throw new Error(`${id}: T:, Q: and K: are required`);
  const notes = rawNotes(block) ?? abcNotes(block, id);
  const midis = fitToNeck(notes.map((n) => n.midi));
  if (!midis) throw new Error(`${id}: wider than the neck`);
  const tonic = key.match(/^([A-G][#b]?)/)![1];
  const c = classify(midis);
  const scale =
    c.base === 'chromatic'
      ? `${tonic}_chromatic`
      : (c.scales.find((s) => s.startsWith(`${tonic}_`)) ?? c.scales[0]);
  return {
    id,
    title,
    rank,
    tempoBpm: quarterBpm(q, id),
    scale,
    notes: notes.map((n, i) => `${NAMES[midis[i] % 12]}${Math.floor(midis[i] / 12) - 1}:${beatsText(n.beats)}`).join(' '),
    source: from,
    base: c.base,
    count: midis.length,
  };
});

const ids = new Set<string>();
for (const t of tunes) {
  if (ids.has(t.id)) throw new Error(`Duplicate id ${t.id}`);
  ids.add(t.id);
}
const titles = new Set<string>();
for (const t of tunes) {
  if (titles.has(t.title)) throw new Error(`Duplicate title ${t.title}`);
  titles.add(t.title);
}
tunes.sort((a, b) => a.rank - b.rank);

const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const body = tunes
  .map(
    (t) =>
      `  {\n    id: ${q(t.id)},\n    title: ${q(t.title)},\n    rank: ${t.rank},\n    tempoBpm: ${t.tempoBpm},\n` +
      `    scale: ${q(t.scale)},\n    source: ${q(t.source)},\n    notes: ${q(t.notes)},\n  },`,
  )
  .join('\n');
writeFileSync(
  join(DIR, 'library.ts'),
  `// GENERATED by scripts/build-library.ts from library.abc — do not edit; run \`npm run library\`.

export interface LibraryTune {
  /** Stable, hyphen-free id; it prefixes the Melody id and names the bundled audio clip. */
  id: string;
  title: string;
  /** Difficulty rank, 1–9. */
  rank: number;
  /** The tune's own tempo, quarter notes per minute. */
  tempoBpm: number;
  /** "<Root>_<family>" derived from the notes; "<Root>_chromatic" when they need more than one key. */
  scale: string;
  /** Where the notes were taken from. */
  source: string;
  /** "pitch:beats" tokens, e.g. "E4:1 D4:2". */
  notes: string;
}

export const TUNES: readonly LibraryTune[] = [
${body}
];
`,
);

for (let r = MIN_RANK; r <= MAX_RANK; r++) {
  const of = tunes.filter((t) => t.rank === r);
  console.log(
    `L${r} (${of.length}): ` + of.map((t) => `${t.id} ${t.count}${t.base[0].toUpperCase()} ♩${t.tempoBpm}`).join(' · '),
  );
}
console.log(`${tunes.length} tunes -> src/services/melody/library.ts`);
