// Writes what ships inside the app for the first levels (spec 024), so a new learner plays at once, offline:
//   - src/services/tunes/shippedTunes.ts: those tunes WITH their answer, and the hash of their shipped clip (a re-voiced
//     clip on the server is fetched, an unchanged one is not);
//   - the MELODY_CLIPS block of src/services/audio/bundled.ts: Metro bundles only the clips it requires.
// Run after `npm run library` and after rendering the clips:
//
//   server/node_modules/.bin/tsx scripts/build-shipped-tunes.ts
//
// "The first levels" is LOCAL_ANSWER_MAX_LEVEL in server/src/game/config.ts (and SHIPPED_MAX_LEVEL in
// assets/guitar-rig/render_library.py): the server sends the answer of exactly those tunes in its catalog.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { LOCAL_ANSWER_MAX_LEVEL } from '../server/src/game/config';
import { TUNES } from '../server/src/tunes/library.data';
import { movesOf } from '../server/src/tunes/moves';
import { parseNotes } from '../server/src/tunes/notes';

const ROOT = join(__dirname, '..');
const CLIPS = join(ROOT, 'assets', 'app', 'audio', 'melodies');
/** The first melody's opening has a clip of its own (EXCERPTS in render_library.py). */
const EXCERPT_CLIPS = ['fifthfirst'];

const shipped = TUNES.filter((t) => t.rank <= LOCAL_ANSWER_MAX_LEVEL);
const tunes = shipped.map((t) => {
  const clip = readFileSync(join(CLIPS, `${t.id}.m4a`));
  const notes = parseNotes(t.notes) ?? [];
  return {
    id: t.id,
    title: t.title,
    rank: t.rank,
    tempoBpm: t.tempoBpm,
    phrases: [...t.phrases],
    beats: notes.map((n) => n.beats),
    scale: t.scale,
    moves: movesOf(t.notes, t.phrases),
    answer: notes.map((n) => n.midi),
    audio: { sha256: createHash('sha256').update(clip).digest('hex'), url: null, bytes: clip.length },
  };
});

writeFileSync(
  join(ROOT, 'src', 'services', 'tunes', 'shippedTunes.ts'),
  `// GENERATED by scripts/build-shipped-tunes.ts — do not edit.
// The tunes of the first levels ship inside the app with their answer and clip, so the first launch plays at once, offline.
import type { LibraryTune } from './types';

export const SHIPPED_TUNES: readonly LibraryTune[] = ${JSON.stringify(tunes, null, 2)};

/** Tune id → hash of the clip shipped inside the app. */
export const SHIPPED_HASHES: ReadonlyMap<string, string> = new Map(SHIPPED_TUNES.map((t) => [t.id, t.audio.sha256]));
`,
);

const registry = join(ROOT, 'src', 'services', 'audio', 'bundled.ts');
const source = readFileSync(registry, 'utf8');
const start = source.indexOf('/** The clips shipped inside the app');
const end = source.indexOf('};', start) + 3;
const block =
  `/** The clips shipped inside the app (the first levels), then the openings voiced on their own (EXCERPTS). The rest are downloaded. */\n` +
  `export const MELODY_CLIPS: Record<string, number> = {\n` +
  [...shipped.map((t) => t.id), ...EXCERPT_CLIPS].map((id) => `  ${id}: require('../../../assets/app/audio/melodies/${id}.m4a'),\n`).join('') +
  `};\n`;
writeFileSync(registry, source.slice(0, start) + block + source.slice(end));
console.log(`${tunes.length} tunes shipped (levels 1-${LOCAL_ANSWER_MAX_LEVEL}), ${(tunes.reduce((n, t) => n + t.audio.bytes, 0) / 1e6).toFixed(1)} MB of clips`);
