// Writes docs/melody-check.md: the sheet for checking the library by ear (play every tune on a guitar
// once and fix wrong notes in library.abc). Tunes written from memory come first, then those taken
// from a score. Each tune gets a tab in
// one hand position, so it can be played without working out fingerings, and the leaps that most
// often betray a misremembered note (wider than a fifth) are flagged.
//
//   server/node_modules/.bin/tsx scripts/melody-check.ts
import { writeFileSync } from 'node:fs';
import { FretPosition, STRING_LABELS, positionsForMidi } from '../src/lib/fretboard';
import { noteName } from '../src/lib/pitchNote';
import { parseMelody } from '../src/services/melody/classify';
import { LIBRARY } from '../src/services/melody/curated';

const LEAP_FLAG = 7; // semitones; wider than a perfect fifth

/** Fingering that keeps the hand still: each note on the position nearest the previous fret. */
function tab(midis: number[]): FretPosition[] {
  const out: FretPosition[] = [];
  for (const m of midis) {
    const options = positionsForMidi(m);
    const prev = out[out.length - 1]?.fret ?? 2;
    options.sort((a, b) => Math.abs(a.fret - prev) - Math.abs(b.fret - prev) || a.fret - b.fret);
    out.push(options[0]);
  }
  return out;
}

const fromMemory = (t: { source: string }) => /from memory/.test(t.source) && !/checked by ear/.test(t.source);
const tunes = [...LIBRARY].sort((a, b) => Number(fromMemory(b)) - Number(fromMemory(a)) || a.rank - b.rank);

const lines: string[] = [
  '# Melody check (T088)',
  '',
  'Generated by `scripts/melody-check.ts`; regenerate after editing the library. Play each tune once',
  'on the guitar from the tab, tick it when it sounds right, and fix it in',
  '`src/services/melody/library.abc` (then `npm run library`) when it does not. ⚠ marks a leap wider',
  'than a fifth — the usual sign of a wrong note.',
  'Rhythm is played back but not graded, so a wrong duration matters less than a wrong pitch.',
  '',
];
let section = '';
for (const t of tunes) {
  const from = fromMemory(t) ? 'Written from memory (check first)' : 'Taken from a score';
  if (from !== section) {
    section = from;
    lines.push(`## ${from}`, '');
  }
  const midis = parseMelody(t.notes).map((n) => n.midi);
  const leaps = midis.slice(1).map((m, i) => Math.abs(m - midis[i]));
  const flags = leaps.filter((l) => l > LEAP_FLAG).length;
  const fingering = tab(midis)
    .map((p, i) => `${noteName(midis[i])}=${STRING_LABELS[p.string]}${p.fret}`)
    .join(' ');
  lines.push(
    `- [ ] **${t.title}** · level ${t.rank} · ${midis.length} notes · ♩ ${t.tempoBpm} · \`${t.id}\`${flags ? ` · ⚠ ${flags} wide leap${flags > 1 ? 's' : ''}` : ''}`,
    `  ${fingering}`,
    `  source: ${t.source}`,
  );
}
lines.push('');

writeFileSync('docs/melody-check.md', lines.join('\n'));
console.log(`docs/melody-check.md: ${tunes.length} tunes`);
